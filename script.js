function openBlessureModal(id = null) {
    document.querySelectorAll('#blessureModal input, #blessureModal select').forEach(el => el.value = '');
    populateMemberSelects();
    if (id) {
        const b = appData.injuries.find(x => x.id == id);
        document.getElementById('blessureId').value = b.id;
        document.getElementById('blessurePlayer').value = b.memberId;
        document.getElementById('blessureType').value = b.type || '';
        document.getElementById('blessureDuree').value = b.duration || '';
        document.getElementById('blessureDate').value = b.date || '';
        document.getElementById('blessureStatut').value = b.status || 'En soin';
    } else { document.getElementById('blessureDate').valueAsDate = new Date(); }
    openModal('blessureModal');
}

function saveBlessure() {
    const id = document.getElementById('blessureId').value;
    const injury = {
        id: id || Date.now().toString(), memberId: document.getElementById('blessurePlayer').value,
        type: document.getElementById('blessureType').value, duration: document.getElementById('blessureDuree').value,
        date: document.getElementById('blessureDate').value, status: document.getElementById('blessureStatut').value
    };
    if (id) { appData.injuries[appData.injuries.findIndex(b => b.id == id)] = injury; }
    else { appData.injuries.push(injury); }
    saveData(); renderAll(); closeModal('blessureModal'); showToast(translations.injury_saved[currentLang]);
}

function renderInfirmerie() {
    const tbody = document.getElementById('infirmerieTable'); if (!tbody) return;
    tbody.innerHTML = '';
    appData.injuries.forEach(b => {
        const member = appData.members.find(m => m.id == b.memberId);
        const name = member ? getFullName(member) : 'Unknown';
        let daysLeftText = '-';
        if (b.date && b.duration && b.status === "En soin") {
            const injuryDate = new Date(b.date); const today = new Date();
            const endDate = new Date(injuryDate); endDate.setDate(injuryDate.getDate() + Number(b.duration));
            const daysLeft = Math.ceil((endDate - today) / (1000 * 60 * 60 * 24));
            daysLeftText = daysLeft > 0 ? `<span style="color: #ff0033; font-weight: 800;">${daysLeft} j</span>` : `<span style="color: var(--gold-dark); font-weight: 800;">0 j (Dépassé)</span>`;
        } else if (b.status === "Guéri" || b.status === "Reprise") { daysLeftText = `<span style="color: var(--gold-dark); font-weight: 800;">Terminé</span>`; }
        let statusBadge = `<span class="badge badge-muted">-</span>`;
        if (b.status === "En soin") statusBadge = `<span class="badge badge-warning">${translations.in_treatment[currentLang]}</span>`;
        else if (b.status === "Guéri") statusBadge = `<span class="badge badge-success">${translations.recovered[currentLang]}</span>`;
        else if (b.status === "Reprise") statusBadge = `<span class="badge badge-info">${translations.resumed[currentLang]}</span>`;
        const actionsHtml = `<button class="btn btn-sm btn-secondary" onclick="openBlessureModal('${b.id}')" title="${translations.edit[currentLang]}"><i class="fas fa-edit"></i></button><button class="btn btn-sm btn-danger" onclick="deleteBlessure('${b.id}')" title="${currentLang === 'fr' ? 'Supprimer' : 'Delete'}"><i class="fas fa-trash"></i></button>`;
        tbody.innerHTML += `<tr><td>${name}</td><td>${b.type || '-'}</td><td>${b.date || '-'}</td><td>${b.duration || '-'} j</td><td>${daysLeftText}</td><td>${statusBadge}</td><td style="text-align:right; white-space: nowrap;">${actionsHtml}</td></tr>`;
    });
}

function deleteBlessure(id) {
    appData.injuries = appData.injuries.filter(b => b.id != id);
    saveData(); renderAll(); showToast(translations.injury_deleted[currentLang], true);
}

