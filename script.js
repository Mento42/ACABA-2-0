function paySanction(id) {
    const s = appData.sanctions.find(x => x.id == id); if (!s) return;
    const total = Number(s.amount || 0), alreadyPaid = Number(s.amountPaid || 0);
    const remaining = total - alreadyPaid;
    const input = prompt(`${currentLang === 'fr' ? 'Montant à encaisser (Reste: ' + remaining + ' F)' : 'Amount to collect (Remaining: ' + remaining + ' F)'}`, remaining);
    if (input !== null) {
        const amountToPay = Number(input);
        if (!isNaN(amountToPay) && amountToPay > 0) {
            s.amountPaid = alreadyPaid + amountToPay;
            saveData(); renderAll(); showToast(translations.payment_saved[currentLang]);
        } else if (amountToPay !== 0) { showToast(currentLang === 'fr' ? "Montant invalide." : "Invalid amount.", true); }
    }
}

