function renderDashboard() {
    document.getElementById('totalMembers').innerText = appData.members.length;
    const totalCollected = appData.contributions.reduce((sum, c) => sum + Number(c.amount), 0);
    document.getElementById('totalCollected').innerText = totalCollected.toLocaleString();
    document.getElementById('totalMatches').innerText = appData.matches.length;

    // --- FONCTION HELPER POUR PARSER LES DATES ---
    function parseMatchDate(dateStr) {
        if (!dateStr) return null;
        const parts = dateStr.split('-');
        if (parts.length === 3) {
            const year = parseInt(parts[0]);
            const month = parseInt(parts[1]) - 1;
            const day = parseInt(parts[2]);
            if (!isNaN(year) && !isNaN(month) && !isNaN(day)) {
                const d = new Date(year, month, day);
                d.setHours(0, 0, 0, 0);
                return d;
            }
        }
        try {
            const d = new Date(dateStr);
            if (!isNaN(d.getTime())) { d.setHours(0, 0, 0, 0); return d; }
        } catch(e) {}
        return null;
    }

    const today = new Date();
    today.setHours(0, 0, 0, 0);

    // --- 1. CHARGER LES MATCHS FUTURS EXISTANTS ---
    const upcomingMatches = appData.matches
        .map(m => ({ ...m, parsedDate: parseMatchDate(m.date) }))
        .filter(m => m.parsedDate && m.parsedDate >= today)
        .sort((a, b) => a.parsedDate - b.parsedDate);

    const nextMatchElement = document.getElementById('nextMatchDate');

    if (upcomingMatches.length > 0) {
        // ✅ Il y a déjà un match futur enregistré → l'afficher
        const nextMatch = upcomingMatches[0];
        const dateOptions = { weekday: 'short', day: '2-digit', month: 'short' };
        let nextMatchText = nextMatch.parsedDate.toLocaleDateString(
            currentLang === 'fr' ? 'fr-FR' : 'en-US', 
            dateOptions
        );
        
        let nextMatchInfo = '';
        if (nextMatch.type === 'amical' && nextMatch.opponent) {
            nextMatchInfo = `<br><span style="font-size:12px; color:var(--text-sec);">vs ${nextMatch.opponent}</span>`;
        } else if (nextMatch.type === 'hebdomadaire') {
            nextMatchInfo = `<br><span style="font-size:12px; color:var(--text-sec);">🏆 ${currentLang === 'fr' ? 'Hebdo' : 'Weekly'}</span>`;
        } else if (nextMatch.type === 'intergeneration') {
            nextMatchInfo = `<br><span style="font-size:12px; color:var(--text-sec);">⚔️ ${currentLang === 'fr' ? 'Intergen' : 'Intergen'}</span>`;
        }
        
        nextMatchElement.innerHTML = nextMatchText + nextMatchInfo;
        
    } else {
        // 🔄 PAS DE MATCH FUTUR → Calculer automatiquement le prochain match hebdomadaire
        const hebdoMatches = appData.matches
            .filter(m => m.type === 'hebdomadaire')
            .map(m => ({ ...m, parsedDate: parseMatchDate(m.date) }))
            .filter(m => m.parsedDate)
            .sort((a, b) => b.parsedDate - a.parsedDate);
        
        let nextHebdoDate = null;
        
        if (hebdoMatches.length > 0) {
            // Basé sur le dernier match joué
            const lastMatch = hebdoMatches[0];
            const lastDayOfWeek = lastMatch.parsedDate.getDay();
            nextHebdoDate = new Date(today);
            const daysUntilNext = ((lastDayOfWeek - today.getDay() + 7) % 7) || 7;
            nextHebdoDate.setDate(today.getDate() + daysUntilNext);
        } else {
            // Aucun match joué → prendre le prochain dimanche par défaut
            nextHebdoDate = new Date(today);
            const daysUntilSunday = (7 - today.getDay()) % 7 || 7;
            nextHebdoDate.setDate(today.getDate() + daysUntilSunday);
        }
        
        const dateOptions = { weekday: 'short', day: '2-digit', month: 'short' };
        const autoDateText = nextHebdoDate.toLocaleDateString(
            currentLang === 'fr' ? 'fr-FR' : 'en-US',
            dateOptions
        );
        
        const year = nextHebdoDate.getFullYear();
        const month = String(nextHebdoDate.getMonth() + 1).padStart(2, '0');
        const day = String(nextHebdoDate.getDate()).padStart(2, '0');
        const dateForInput = `${year}-${month}-${day}`;
        
        nextMatchElement.innerHTML = `
            <div style="font-size:inherit; line-height:1.3;">
                <div>${autoDateText}</div>
                <div style="font-size:11px; color:var(--text-sec); margin-top:4px;">🏆 ${currentLang === 'fr' ? 'Hebdo (auto)' : 'Weekly (auto)'}</div>
                <button onclick="createAutoMatch('${dateForInput}')" 
                    style="margin-top:6px; padding:4px 10px; font-size:11px; background:var(--gold); color:var(--primary); border:none; border-radius:4px; cursor:pointer; font-weight:700; text-transform:uppercase;">
                    <i class="fas fa-plus"></i> ${currentLang === 'fr' ? 'Créer' : 'Create'}
                </button>
            </div>
        `;
    }

    let membersOk = 0, membersPartial = 0, membersLate = 0, totalAnnualDuesCollected = 0;
    const annualTarget = 25000;
    appData.members.forEach(m => {
        let duesPaid = appData.contributions.filter(c => c.memberId == m.id && c.type === "Cotisation Annuelle").reduce((sum, c) => sum + Number(c.amount), 0);
        totalAnnualDuesCollected += duesPaid;
        if (duesPaid >= annualTarget) membersOk++;
        else if (duesPaid >= 15000) membersPartial++;
        else membersLate++;
    });
    document.getElementById('membersOk').innerText = membersOk;
    document.getElementById('membersPartial').innerText = membersPartial;
    document.getElementById('membersLate').innerText = membersLate;

    const goalAmount = appData.members.length * annualTarget;
    const completionRate = goalAmount > 0 ? (totalAnnualDuesCollected / goalAmount) * 100 : 0;
    document.getElementById('completionRate').innerText = completionRate.toFixed(1) + '%';
    document.getElementById('goalAmount').innerText = goalAmount.toLocaleString() + ' F';
    document.getElementById('completionBar').style.width = completionRate + '%';

    renderCategoryChart(); 
    renderContribChart(); 
    renderInfirmaryDashboard();
}

