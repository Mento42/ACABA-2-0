function saveMatch() {
    const id = document.getElementById('matchId').value;
    const match = {
        id: id || Date.now().toString(), type: document.getElementById('matchType').value,
        date: document.getElementById('matchDate').value, trimester: document.getElementById('matchTrimestre').value,
        opponent: document.getElementById('matchAdversaire').value, score1: document.getElementById('matchScore1').value,
        score2: document.getElementById('matchScore2').value, manOfMatch: document.getElementById('matchHommeMatch').value,
        refereeCentral: document.getElementById('matchRefereeCentral').value, commissioner: document.getElementById('matchCommissioner').value,
        judge1: document.getElementById('matchJudge1').value, judge2: document.getElementById('matchJudge2').value,
        scorers: document.getElementById('matchScorers').value, assists: document.getElementById('matchAssists').value,
        sheet1: document.getElementById('matchSheet1').value, sheet2: document.getElementById('matchSheet2').value
    };
    if (id) { appData.matches[appData.matches.findIndex(m => m.id == id)] = match; }
    else { appData.matches.push(match); }
    saveData(); renderAll(); closeModal('matchModal'); showToast(translations.match_saved[currentLang]);
}

function deleteMatch(id) {
    appData.matches = appData.matches.filter(m => m.id != id);
    saveData(); renderAll(); showToast(translations.match_deleted[currentLang], true);
}

